-- Migration 20261003210003_participants_tickets
-- Phase 2 / part 3 of 7: the people and their tickets.
--
-- Decisions documented here:
--   * Buyer vs participant: the buyer (orders.buyer_* ) pays; every ticket belongs to
--     exactly one participant. One buyer may buy several tickets, so participant rows are
--     per unit and carry the full data set the operations team needs at the door.
--   * Participant fields are stored normalized (national_id digits only, email lowercase,
--     phone digits only). The checks mirror the Phase 1 domain rules
--     (supabase/functions/_shared/domain/participant.ts) and reject only what is clearly
--     broken; they do not invent stricter policies.
--   * Duplicate participant detection is deliberately NOT a unique constraint yet: whether
--     a cédula may appear twice is an open decision (docs/data-model.md section 6.1).
--     The (event_id, national_id) index makes the check cheap once the policy is confirmed.
--   * tickets.participant_id is nullable AND unique: a ticket may be issued before the
--     buyer assigns a person to it, but two tickets can never point at the same participant.
--   * The ticket token (`TKT_` + 20 Crockford base32 characters, 100 bits) is generated by
--     the trusted backend (Phase 1 `ticket-token.ts`) and is the only value encoded in the
--     QR. The database enforces its format and uniqueness; it never stores a QR image.
--   * Even though event_id is denormalized here (it is reachable through the order), it is
--     kept because duplicate detection, capacity reporting and the operational export all
--     filter by event. The backend derives it from the order/order_item; a wrong value is a
--     backend bug, which is why the single-column foreign keys stay explicit.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- participants
-- ---------------------------------------------------------------------------
create table public.participants (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events (id) on delete restrict,
  -- Personal data is never deleted silently: `restrict` forces an explicit erasure flow.
  order_id uuid not null references public.orders (id) on delete restrict,
  -- Which order line (sales stage / ticket type) this unit came from. Nullable because
  -- Phase 3 may allow buying first and assigning participants later.
  order_item_id uuid references public.order_items (id) on delete restrict,
  first_name text not null
    check (length(btrim(first_name)) between 1 and 80 and first_name !~ '[\n\r\t]'),
  last_name text not null
    check (length(btrim(last_name)) between 1 and 80 and last_name !~ '[\n\r\t]'),
  -- Cédula (or foreign document number), digits only after normalization: 6 to 12 digits.
  national_id text not null
    check (national_id ~ '^[0-9]{6,12}$'),
  email text not null
    check (
      email = lower(email)
      and email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
      and length(email) <= 254
    ),
  -- Canonical form produced by the domain normalizer is `57` + 7..10 digits. The check is
  -- intentionally a digits-only sanity bound (same floor as orders.buyer_phone) so legacy
  -- or manually imported numbers are not silently rejected.
  phone text not null
    check (phone ~ '^[0-9]{7,15}$'),
  city text not null
    check (length(btrim(city)) between 2 and 80 and city !~ '[\n\r\t]'),
  -- Handle without `@`, lowercase, as produced by `normalizeInstagram`.
  instagram text
    check (instagram is null or instagram ~ '^[a-z0-9._]{1,30}$'),
  -- Extension point: future optional fields (dietary restrictions, t-shirt size, …) live
  -- here, so adding one does not require a migration. Must always be a JSON object.
  extra_fields jsonb not null default '{}'::jsonb
    check (jsonb_typeof(extra_fields) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.participants is
  'One row per ticketed person: name, cédula, contact data and the extension point (extra_fields). Personal data: never exposed through public endpoints, never logged raw.';

-- Duplicate-registration detection (policy pending): "does this cédula already exist for this event?"
create index participants_event_national_id_idx on public.participants (event_id, national_id);
create index participants_email_idx on public.participants (email);
create index participants_order_id_idx on public.participants (order_id);
create index participants_order_item_id_idx on public.participants (order_item_id);

create trigger participants_set_updated_at
  before update on public.participants
  for each row execute function app_private.set_updated_at();

-- ---------------------------------------------------------------------------
-- tickets
-- ---------------------------------------------------------------------------
create table public.tickets (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events (id) on delete restrict,
  order_id uuid not null references public.orders (id) on delete restrict,
  order_item_id uuid not null references public.order_items (id) on delete restrict,
  -- Nullable + unique: assignment is optional at issuance, sharing a participant is not.
  participant_id uuid unique references public.participants (id) on delete restrict,
  ticket_type_id uuid not null references public.ticket_types (id) on delete restrict,
  -- The authoritative value behind the QR. Generated by the backend from a CSPRNG.
  token text not null unique
    check (token ~ '^TKT_[0-9A-HJKMNP-TV-Z]{20}$'),
  status public.ticket_status not null default 'ACTIVE',
  -- Frozen copy of what this unit cost (from the order line); later price changes never
  -- rewrite it. A fully discounted ticket is legitimately 0.
  price_paid_cents bigint not null
    check (price_paid_cents >= 0),
  issued_at timestamptz not null default now(),
  -- Set when the ticket leaves ACTIVE (cancelled or refunded). Meaningless on ACTIVE rows
  -- and intentionally not tied to a single status value: a refund flows through cancelled.
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.tickets is
  'One row per admission. The opaque token is the QR payload; an attendance row is the only proof of use. Statuses mirror the Phase 1 state machine: ACTIVE / CANCELLED / REFUNDED.';

create index tickets_event_id_idx on public.tickets (event_id);
create index tickets_event_status_idx on public.tickets (event_id, status);
create index tickets_order_id_idx on public.tickets (order_id);
create index tickets_order_item_id_idx on public.tickets (order_item_id);
create index tickets_ticket_type_id_idx on public.tickets (ticket_type_id);

create trigger tickets_set_updated_at
  before update on public.tickets
  for each row execute function app_private.set_updated_at();
