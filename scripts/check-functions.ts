/**
 * Type checks every Edge Function and the shared core with Deno, which is the runtime
 * that actually executes them.
 *
 * `tsc` cannot do this job: function entrypoints use Deno globals (`Deno.serve`,
 * `Deno.env`), and only Deno resolves the `npm:` specifiers declared in each
 * `deno.json`.
 *
 * IMPORTANT — why `--config` is passed explicitly:
 * Deno's configuration auto-discovery resolves relative to the CURRENT WORKING DIRECTORY,
 * so from the repository root it finds `tsconfig.json` (the Node-side project) and applies
 * its `lib`/`types`, which removes the Deno/web globals and produces bogus errors such as
 * "Cannot find name 'console'". Passing `--config` per target makes the check
 * deterministic and mirrors what the Supabase deployer does (it uses the FUNCTION's own
 * deno.json).
 *
 * Usage: npm run functions:check
 */

import { spawnSync } from "node:child_process";
import { existsSync, readdirSync } from "node:fs";
import path from "node:path";

const FUNCTIONS_DIR = path.join("supabase", "functions");
const SHARED_DIR = path.join(FUNCTIONS_DIR, "_shared");
const DENO_BIN = path.join("node_modules", "deno", "bin.cjs");
/** Generated by `npm run types:generate`; it is a build artifact, not source. */
const GENERATED_TYPES = path.join(SHARED_DIR, "db", "database.types.ts");

function walkTypeScriptFiles(directory: string): string[] {
  const collected: string[] = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collected.push(...walkTypeScriptFiles(entryPath));
      continue;
    }
    if (entry.name.endsWith(".ts") && entryPath !== GENERATED_TYPES) {
      collected.push(entryPath);
    }
  }
  return collected;
}

function functionDirectories(): string[] {
  if (!existsSync(FUNCTIONS_DIR)) {
    return [];
  }
  return readdirSync(FUNCTIONS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_"))
    .map((entry) => entry.name)
    .filter((name) => existsSync(path.join(FUNCTIONS_DIR, name, "index.ts")))
    .sort();
}

function check(label: string, configPath: string, files: readonly string[]): boolean {
  if (files.length === 0) {
    return true;
  }
  console.log(`deno check (${label}): ${String(files.length)} file(s)`);
  const result = spawnSync(
    process.execPath,
    [DENO_BIN, "check", "--config", configPath, ...files],
    {
      stdio: "inherit",
    },
  );
  return result.status === 0;
}

function main(): void {
  if (!existsSync(DENO_BIN)) {
    console.error(
      `Deno is not installed locally (expected ${DENO_BIN}). Run \`npm install\` first.`,
    );
    process.exit(1);
  }

  const sharedFiles = existsSync(SHARED_DIR) ? walkTypeScriptFiles(SHARED_DIR).sort() : [];
  const sharedConfig = path.join(SHARED_DIR, "deno.json");

  let ok = true;
  if (sharedFiles.length > 0) {
    ok = check("_shared", sharedConfig, sharedFiles) && ok;
  }

  const functions = functionDirectories();
  for (const name of functions) {
    ok =
      check(name, path.join(FUNCTIONS_DIR, name, "deno.json"), [
        path.join(FUNCTIONS_DIR, name, "index.ts"),
      ]) && ok;
  }

  if (!ok) {
    console.error("deno check failed. Edge Functions would not deploy with these types.");
    process.exit(1);
  }

  console.log(
    `deno check ok: ${String(functions.length)} function entrypoint(s), ${String(sharedFiles.length)} shared file(s)`,
  );
}

main();
